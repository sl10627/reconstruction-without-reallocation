OUT, DATA = ROOT / "output", ROOT / "data"

_cache = {}
def csv(name, folder=OUT):
    key = (folder, name)
    if key not in _cache:
        _cache[key] = pd.read_csv(folder / name)
    return _cache[key]

def cell(name, col, folder=OUT, **eq):
    """Single value from `name`.csv at row matching all eq filters, column `col`.
    String filters match by substring (case-insensitive); numeric by equality."""
    d = csv(name, folder)
    m = pd.Series(True, index=d.index)
    for k, v in eq.items():
        if isinstance(v, str):
            m &= d[k].astype(str).str.contains(v, case=False, regex=False)
        else:
            m &= (d[k] == v)
    sub = d.loc[m, col]
    if len(sub) != 1:
        raise LookupError(f"{name}.csv[{col}] with {eq} -> {len(sub)} rows (want 1)")
    return float(sub.iloc[0])


"""Self-check: verify every hard-coded number in the paper prose against the
current pipeline outputs.

The paper's *tables* are auto-generated by 17_make_tables.py, so they cannot
drift from the code. The risk is the numbers typed by hand into the prose of
paper/paper_word.tex (and the Word draft): coefficients, p-values, CIs, ranges.
This script re-reads the fresh output/*.csv and data/*.csv and checks each such
claim. Run it after re-running the pipeline (or after any regression change):

    python code/verify_numbers.py

Exit code 0 => every prose number matches. Exit code 1 => at least one drifted;
the offending rows are printed with the claimed vs. actual value.

Each check stores the claim as it appears in the paper (already rounded) and an
extractor that pulls the full-precision value from a CSV. A claim passes when the
actual value, rounded to the claim's decimal places, equals the claim (with a
small absolute fallback tolerance for the last digit).
"""

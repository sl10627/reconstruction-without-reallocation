def match(claimed, actual, decimals):
    """Pass if actual rounds to the claim, or is within half a ULP of the last
    printed digit (covers banker's-rounding edge cases)."""
    if actual is None or (isinstance(actual, float) and np.isnan(actual)):
        return False
    tol = 0.5 * 10 ** (-decimals) + 1e-9
    return (round(actual, decimals) == round(claimed, decimals)) or (abs(actual - claimed) <= tol)


def main():
    rows, n_fail = [], 0
    for section, desc, claimed, dec, fn in CHECKS:
        try:
            actual = fn()
            ok = match(claimed, actual, dec)
            act_s = f"{actual:.{max(dec,3)}f}"
        except Exception as e:                      # missing CSV / row -> hard fail
            ok, act_s = False, f"ERR: {e}"
        n_fail += not ok
        rows.append((section, desc, f"{claimed:+.{dec}f}", act_s, "ok" if ok else "MISMATCH"))

    w0 = max(len(r[0]) for r in rows)
    w1 = max(len(r[1]) for r in rows)
    w2 = max(len(r[2]) for r in rows)
    w3 = max(len(r[3]) for r in rows)
    print(f"{'SECTION':<{w0}}  {'CLAIM':<{w1}}  {'PAPER':>{w2}}  {'PIPELINE':>{w3}}  STATUS")
    print("-" * (w0 + w1 + w2 + w3 + 16))
    for sec, desc, cl, ac, st in rows:
        flag = "" if st == "ok" else "  <<<<<<"
        print(f"{sec:<{w0}}  {desc:<{w1}}  {cl:>{w2}}  {ac:>{w3}}  {st}{flag}")

    total = len(rows)
    print("-" * (w0 + w1 + w2 + w3 + 16))
    if n_fail == 0:
        print(f"ALL {total} prose numbers match the current pipeline outputs.")
    else:
        print(f"{n_fail} of {total} checks MISMATCH -- prose is out of sync with the pipeline.")
    return 1 if n_fail else 0


if __name__ == "__main__":
    sys.exit(main())
